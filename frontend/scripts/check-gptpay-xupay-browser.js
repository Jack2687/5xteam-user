(async () => {
  const fixture = window.gptPayFixture
  if (!fixture) throw new Error('Requires isolated GPTPay preview')
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
  const assert = (ok, message) => { if (!ok) throw new Error(message) }
  const wait = async fn => { for (let i = 0; i < 400; i++) { if (fn()) return; await pause(25) } throw new Error('UI wait timed out') }
  const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text)
  const click = async text => { await wait(() => button(text) && !button(text).disabled); button(text).click(); await pause(100) }
  const field = text => text === '支付国家' ? document.getElementById('pro-payment-country') : [...document.querySelectorAll('label.field')].find(l => l.querySelector('span')?.textContent.trim() === text)?.querySelector('input,select,textarea')
  const fill = async (text, value) => { const el = field(text); assert(el, 'Missing field: ' + text); el.value = value; el.dispatchEvent(new Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); await pause(150) }
  await click('Pro 全自动配置')
  await wait(() => field('开通供应商') && !field('开通供应商').disabled)
  await fill('开通供应商', 'xupay')
  await wait(() => field('序付 API 地址') && !field('开通套餐').disabled)
  assert(field('序付 API 地址').value === 'http://104.160.172.162:5496/api/v1', 'XUPAY default URL')
  assert(field('序付 API Key').value === '' && !field('序付 API Key').placeholder.includes('已保存'), 'Another provider key leaked')
  assert(field('开通套餐').options.length === 2 && !field('开通套餐').querySelector('[value="pro50"]'), 'Unsupported plan offered')
  await fill('开通套餐', 'pro20')
  await fill('序付 API Key', 'fixture-xupay-key')
  const terms = document.querySelector('.cmsnav-terms input')
  assert(terms && !terms.checked, 'Missing terms checkbox')
  terms.click()
  await click('保存 Pro 配置')
  await wait(() => fixture.config.provider === 'xupay' && !field('开通套餐').disabled)
  await wait(() => field('开通套餐').textContent.includes('1.25 R'))
  assert(field('序付 API Key').value === '', 'Saved key remains in field')
  await fill('开通供应商', 'tokenseek')
  await wait(() => field('GPTPay API 地址') && !field('开通套餐').disabled)
  assert(field('GPTPay API 地址').value.includes('tokenseek') && field('GPTPay API Key').value === '', 'Provider isolation failed')
  await fill('开通供应商', 'xupay')
  await wait(() => field('序付 API 地址') && !field('开通套餐').disabled)
  assert(field('开通套餐').value === 'pro20', 'XUPAY profile lost')
  fixture.cards.push({ id: 'xupay-card', name: '隔离测试卡', last4: '4242', exp_year: 2099, exp_month: 12, enabled: true })
  await click('Pro 账号')
  const choose = async title => { document.querySelector('.pro-table [title="更多操作"]').click(); await pause(50); await wait(() => document.querySelector(`.pro-action-menu [title="${title}"]`)); document.querySelector(`.pro-action-menu [title="${title}"]`).click(); await pause(200) }
  await choose('开通 Pro')
  await wait(() => button('确认开通 Pro 20x') && !button('确认开通 Pro 20x').disabled)
  assert(document.querySelector('.pro-recharge-dialog').textContent.includes('序付'), 'Manual confirmation missing XUPAY')
  await click('确认开通 Pro 20x')
  await wait(() => fixture.orders.length === 1)
  const request = fixture.requests.find(r => r.path.endsWith('/recharge'))
  assert(request.body.provider === 'xupay' && request.body.plan_code === 'pro20', 'Manual route lost XUPAY')
  await click('关闭')
  await choose('全自动开通 Pro / 查看进度与停止')
  await wait(() => button('确认全自动开通 Pro 20x'))
  assert(document.querySelector('.pro-auto-dialog').textContent.includes('序付'), 'Automatic confirmation missing XUPAY')
  await click('确认全自动开通 Pro 20x')
  await wait(() => fixture.requests.some(r => r.method === 'POST' && r.path.endsWith('/auto-pro')))
  assert(fixture.requests.find(r => r.method === 'POST' && r.path.endsWith('/auto-pro')).body.provider === 'xupay', 'Automatic route lost XUPAY')
  await click('关闭')
  await click('GPTPay 供应商')
  await wait(() => field('查询供应商'))
  assert(field('查询供应商').value === 'xupay', 'Query provider default incorrect')
  await click('查询账户信息')
  assert(document.body.textContent.includes('123.45 R') && document.body.textContent.includes('1.00 R'), 'Wallet/fee cents not converted')
  assert(fixture.requests.every(r => r.path.startsWith('/api/')), 'Browser requested supplier directly')
  await click('Pro 全自动配置')
  await wait(() => field('序付 API 地址') && !field('开通套餐').disabled)
  return 'Passed XUPAY: key isolation, persistent config, 5x/20x, real quote units, manual + automatic provider routing, account query, no browser upstream request'
})()
