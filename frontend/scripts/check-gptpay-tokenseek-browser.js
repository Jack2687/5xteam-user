(async () => {
  const fixture = window.gptPayFixture
  if (!fixture) throw new Error('Requires isolated GPTPay preview')
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
  const assert = (ok, text) => { if (!ok) throw new Error(text) }
  const wait = async fn => { for (let i = 0; i < 500; i++) { if (fn()) return; await pause(25) } throw new Error('Tokenseek UI wait timed out') }
  const button = text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text)
  const click = async text => { await wait(() => button(text) && !button(text).disabled); button(text).click(); await pause(80) }
  const field = text => text === '支付国家' ? document.getElementById('pro-payment-country') : [...document.querySelectorAll('label.field')].find(l => l.querySelector('span')?.textContent.trim() === text)?.querySelector('input,select,textarea')
  const fill = async (text, value) => { const el = field(text); assert(el, 'Missing field: ' + text); el.value = value; el.dispatchEvent(new Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); await pause(100) }
  await click('Pro 全自动配置')
  await wait(() => field('开通套餐') && !field('开通套餐').disabled && document.body.innerText.includes('已读取'))
  const codes = [...field('开通套餐').options].map(o => o.value)
  assert(codes.join(',') === 'go,plus,pro5,pro20,pro50,pro5_up,pro20_up,pro50_up,codex_point', 'Nine documented products missing')
  assert(field('开通套餐').querySelectorAll('optgroup').length === 3, 'Product categories missing')
  assert([...field('支付国家').options].map(o => o.value).join(',') === 'PH,EG,CL,US,JP', 'Five documented countries missing')
  await fill('开通套餐', 'pro50')
  await click('使用套餐默认国家（CL）')
  assert(field('支付国家').value === 'CL', 'Pro50 default must be Chile')
  await fill('开通套餐', 'pro50_up')
  assert(button('使用套餐默认国家（PH）') && document.body.innerText.includes('仅支持已有 Plus'), 'Upgrade default/eligibility missing')
  await fill('开通套餐', 'codex_point')
  assert(field('Codex 点数数量').value === '250', 'Point quantity default missing')
  await fill('Codex 点数数量', '251')
  assert(button('保存 Pro 配置').disabled, 'Invalid point increment accepted')
  await fill('Codex 点数数量', '1250')
  await fill('支付国家', 'JP')
  await click('保存 Pro 配置')
  await wait(() => fixture.config.credit_quantity === 1250 && fixture.config.country === 'JP')
  await wait(() => !field('开通套餐').disabled && document.body.innerText.includes('已读取'))
  const points = fixture.tokenseekAccount.plans.find(p => p.planCode === 'codex_point')
  points.availableCountries = ['PH']
  await click('刷新国家与套餐')
  await wait(() => !button('刷新国家与套餐').disabled)
  assert(field('支付国家').value === 'JP' && button('保存 Pro 配置').disabled, 'Quote silently switched chosen country')
  points.availableCountries = ['PH','EG','CL','US','JP']
  fixture.tokenseekAccount.plans = fixture.tokenseekAccount.plans.filter(p => p.planCode !== 'go')
  await click('刷新国家与套餐')
  await wait(() => !button('刷新国家与套餐').disabled)
  assert(field('开通套餐').querySelector('[value="go"]').disabled, 'Unavailable Go offered after quote')
  assert(!button('保存 Pro 配置').disabled, 'Valid existing selection blocked')
  fixture.quoteFailure = true
  await click('刷新国家与套餐')
  await wait(() => document.body.innerText.includes('目录读取失败'))
  assert(document.body.innerText.includes('实际可购买套餐以账户报价为准') && !button('保存 Pro 配置').disabled, 'Cannot repair failed supplier settings')
  fixture.quoteFailure = false
  await click('刷新国家与套餐')
  await wait(() => !button('刷新国家与套餐').disabled)
  const reads = fixture.requests.filter(r => r.path === '/api/gptpay/account').length
  await fill('GPTPay API 地址', 'https://edited.example/api/v1')
  await pause(450)
  assert(fixture.requests.filter(r => r.path === '/api/gptpay/account').length === reads, 'Quote sent saved key for draft address')
  await fill('GPTPay API 地址', 'https://gptpay.tokenseek.app/api/v1')
  await wait(() => !field('开通套餐').disabled && document.body.innerText.includes('已读取'))
  fixture.cards.push({id:'tokenseek-card',name:'测试卡',last4:'4242',exp_year:2099,exp_month:12,enabled:true})
  await click('Pro 账号')
  const choose = async title => { document.querySelector('.pro-table [title="更多操作"]').click(); await pause(30); document.querySelector(`.pro-action-menu [title="${title}"]`).click(); await pause(120) }
  await choose('开通 Pro')
  await wait(() => button('确认开通 Codex 点数') && !button('确认开通 Codex 点数').disabled)
  assert(document.querySelector('.pro-recharge-dialog').textContent.includes('日本 · JP') && document.querySelector('.pro-recharge-dialog').textContent.includes('1250'), 'Manual confirmation lost country/quantity')
  await click('确认开通 Codex 点数')
  await wait(() => fixture.orders.length === 1)
  const req = fixture.requests.find(r => r.path.endsWith('/recharge'))
  assert(req.body.country === 'JP' && req.body.credit_quantity === 1250 && req.body.plan_code === 'codex_point', 'Manual purchase lost selected fields')
  await click('关闭')
  await choose('全自动开通 Pro')
  await wait(() => button('确认全自动开通 Codex 点数') && !button('确认全自动开通 Codex 点数').disabled)
  assert(document.querySelector('.pro-auto-dialog').textContent.includes('日本 · JP'), 'Automatic country confirmation missing')
  await click('确认全自动开通 Codex 点数')
  await wait(() => fixture.requests.some(r => r.method === 'POST' && r.path.endsWith('/auto-pro')))
  const auto = fixture.requests.find(r => r.method === 'POST' && r.path.endsWith('/auto-pro'))
  assert(auto.body.country === 'JP' && auto.body.credit_quantity === 1250 && auto.body.plan_code === 'codex_point', 'Automatic purchase lost selected fields')
  await click('关闭')
  await click('GPTPay 供应商')
  await wait(() => document.querySelector('.orders-table')?.textContent.includes('Codex 点数'))
  assert(document.querySelector('.orders-table').textContent.includes('日本 · JP') && document.querySelector('.orders-table').textContent.includes('1250'), 'Order table missing saved purchase choices')
  return 'Passed: nine plans/three categories, five countries, defaults, points validation, quote availability, selection preservation, saved config, error recovery, no draft credential forwarding, manual/automatic payloads and order display'
})()
