export function currencyOptions(current = '') {
  const options = currencies.map(item => ({ value: item.code, label: item.code + ' · ' + item.name + '（' + item.region + '）' }))
  // Do not erase historical/supplier values just because the dictionary is older.
  if (current && !codes.has(current)) options.unshift({ value: current, label: current + '（原值，EJH 文档未收录，请核实）' })
  return options
}
